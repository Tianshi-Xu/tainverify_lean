#!/usr/bin/env python3
"""wire.py — Auto-wire emitter-generated bridges into MainTheorem.lean.

For each goal N (already has GoalNBridge.lean, 0-sorry, olean built):
  1. ensure  `import denote.gpt_ly4_regen.GoalNBridge`  exists in the import block
  2. flip    `theorem goal_N_full : goal_N_stmt := by sorry ...`
        ->   `theorem goal_N_full : goal_N_stmt := goal_N_cut_to_full prove_goal_N_cut`
  3. delete any redundant local stub
        `theorem goal_N_cut_to_full : goal_N_stmt_cut -> goal_N_stmt := by sorry`
     (these are superseded by the bridge's own cut_to_full once imported)

Preconditions verified per goal (skip + report if any fail):
  - GoalNBridge.lean exists and has NO `sorry`
  - `prove_goal_N_cut` is defined somewhere under denote/gpt_ly4_regen/
  - GoalNBridge.olean exists in .lake/build
  - goal_N_full line currently present (either sorry-stub or already wired)

Usage:
  python3 wire.py <N> [<N2> ...]          # wire specific goals
  python3 wire.py --all-emitted           # wire every emitter bridge not yet wired
  python3 wire.py ... --dry-run           # show planned edits, write nothing
  python3 wire.py ... --no-build          # apply edits but skip final lake build

Exit 0 only if all requested goals wired AND (build skipped OR build green).
"""
import os, sys, re, subprocess, argparse, glob

REPO = os.path.expanduser("~/.openclaw/workspace/tainverify_lean/trainverify")
DEN = os.path.join(REPO, "denote/gpt_ly4_regen")
MT = os.path.join(DEN, "MainTheorem.lean")
OLEAN_DIR = os.path.join(REPO, ".lake/build/lib/lean/denote/gpt_ly4_regen")
MODPREFIX = "denote.gpt_ly4_regen"

# ---- precondition probes -------------------------------------------------

def bridge_path(n):      return os.path.join(DEN, f"Goal{n}Bridge.lean")
def olean_path(n):       return os.path.join(OLEAN_DIR, f"Goal{n}Bridge.olean")

_IMP_RE = re.compile(rf"^import {re.escape(MODPREFIX)}\.Goal(\d+)Bridge\b", re.M)

def bridge_import_closure(goals):
    """Transitive closure of GoalNNBridge files imported (directly or indirectly)
    when MainTheorem imports each goal in `goals`. Returns a set of goal numbers
    whose Bridge file ends up in the import graph. Used to remove their now-redundant
    `goal_NN_cut_to_full := by sorry` stubs: once a Bridge is imported (even purely as a
    transitive prereq of a wired goal), it brings its OWN real `goal_NN_cut_to_full`,
    which collides with any leftover sorry-stub in MainTheorem (`already been declared`).
    intermediate-only prereqs have no `goal_NN_full` line so the normal wire pass skips
    them; this closure catches their stubs."""
    seen = set()
    stack = list(goals)
    while stack:
        n = stack.pop()
        if n in seen:
            continue
        seen.add(n)
        bp = bridge_path(n)
        if not os.path.isfile(bp):
            continue
        for m in _IMP_RE.findall(open(bp, encoding="utf-8", errors="replace").read()):
            mi = int(m)
            if mi not in seen:
                stack.append(mi)
    return seen

def remove_cut_stub(lines, n):
    """Remove a `theorem goal_n_cut_to_full : goal_n_stmt_cut → goal_n_stmt := by sorry`
    stub if present. Returns the action string or None."""
    stub_pat = re.compile(
        rf"^theorem goal_{n}_cut_to_full : goal_{n}_stmt_cut → goal_{n}_stmt := by sorry\s*$")
    for i, l in enumerate(lines):
        if stub_pat.match(l):
            lines.pop(i)
            return f"-stub goal_{n}_cut_to_full @line {i+1}"
    return None

def bridge_ok(n):
    """Return (ok, reason). ok = bridge exists, 0-sorry, olean built, prove_cut reachable."""
    bp = bridge_path(n)
    if not os.path.isfile(bp):
        return False, "no GoalNBridge.lean"
    txt = open(bp, encoding="utf-8", errors="replace").read()
    if re.search(r"\bsorry\b", txt):
        return False, "bridge contains sorry"
    if not os.path.isfile(olean_path(n)):
        return False, "no olean (build bridge first)"
    # prove_goal_N_cut must be defined under DEN
    hit = subprocess.run(
        ["grep", "-rln", rf"theorem prove_goal_{n}_cut\b", DEN],
        capture_output=True, text=True)
    if hit.returncode != 0 or not hit.stdout.strip():
        return False, "prove_goal_N_cut not found"
    return True, "ok"

def emitted_bridges():
    """goal numbers whose bridge self-reports emitter-generated."""
    out = []
    for bp in glob.glob(os.path.join(DEN, "Goal*Bridge.lean")):
        head = open(bp, encoding="utf-8", errors="replace").read(2000)
        if re.search(r"EMITTER-GENERATED|AUTO-GENERATED by bridge_emitter|emit2\.py|renderer_uni", head):
            m = re.match(r"Goal(\d+)Bridge\.lean", os.path.basename(bp))
            if m:
                out.append(int(m.group(1)))
    return sorted(out)

# ---- MainTheorem state ---------------------------------------------------

def already_wired(lines, n):
    pat = re.compile(rf"^theorem goal_{n}_full : goal_{n}_stmt := goal_{n}_cut_to_full prove_goal_{n}_cut\b")
    return any(pat.match(l) for l in lines)

def has_sorry_cut_stub(lines, n):
    """True if goal_n's cut_to_full is still a sorry-stub in MainTheorem (the REAL
    'not yet wired' signal — the `goal_n_full` line is always present in its final form
    regardless, so `already_wired` alone is not enough to decide)."""
    pat = re.compile(rf"^theorem goal_{n}_cut_to_full : goal_{n}_stmt_cut \u2192 goal_{n}_stmt := by sorry\s*$")
    return any(pat.match(l) for l in lines)

def needs_wire(lines, n):
    """A goal needs wiring iff its cut_to_full is still a sorry-stub. Importing its Bridge
    (which DEFINES the real cut_to_full) + deleting the stub is the wiring action."""
    return has_sorry_cut_stub(lines, n)

def has_full_line(lines, n):
    pat = re.compile(rf"^theorem goal_{n}_full : goal_{n}_stmt :=")
    return any(pat.match(l) for l in lines)

def has_import(lines, n):
    pat = re.compile(rf"^import {re.escape(MODPREFIX)}\.Goal{n}Bridge\b")
    return any(pat.match(l) for l in lines)

# ---- editing -------------------------------------------------------------

def wire_one(lines, n):
    """Mutate `lines` (list[str]) in place for goal n. Return list of action strings."""
    actions = []

    # (1) import — insert after the LAST existing `import denote.gpt_ly4_regen.GoalXXXBridge`
    if not has_import(lines, n):
        imp = f"import {MODPREFIX}.Goal{n}Bridge  -- goal_{n}_cut_to_full (wired by wire.py)\n"
        last_imp = -1
        for i, l in enumerate(lines):
            if re.match(rf"^import {re.escape(MODPREFIX)}\.Goal\d+Bridge\b", l):
                last_imp = i
        if last_imp < 0:
            # fallback: after last `import denote.gpt_ly4_regen.` line at all
            for i, l in enumerate(lines):
                if l.startswith(f"import {MODPREFIX}."):
                    last_imp = i
        lines.insert(last_imp + 1, imp)
        actions.append(f"+import Goal{n}Bridge @line {last_imp+2}")

    # (2) flip the full line
    full_pat = re.compile(rf"^theorem goal_{n}_full : goal_{n}_stmt := by sorry.*$")
    wired = f"theorem goal_{n}_full : goal_{n}_stmt := goal_{n}_cut_to_full prove_goal_{n}_cut"
    for i, l in enumerate(lines):
        if full_pat.match(l):
            lines[i] = wired + "\n"
            actions.append(f"~full goal_{n} @line {i+1}")
            break

    # (3) delete redundant local cut_to_full sorry-stub if present
    stub_pat = re.compile(rf"^theorem goal_{n}_cut_to_full : goal_{n}_stmt_cut \u2192 goal_{n}_stmt := by sorry\s*$")
    for i, l in enumerate(list(lines)):
        if stub_pat.match(l):
            actions.append(f"-stub goal_{n}_cut_to_full @line {i+1}")
            lines.remove(l)
            break

    return actions

# ---- main ----------------------------------------------------------------

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("goals", nargs="*", type=int)
    ap.add_argument("--all-emitted", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--no-build", action="store_true")
    args = ap.parse_args()

    lines = open(MT, encoding="utf-8").read().splitlines(keepends=True)

    if args.all_emitted:
        targets = [n for n in emitted_bridges() if needs_wire(lines, n)]
    else:
        targets = args.goals
    if not targets:
        print("[wire] nothing to do (no targets / all already wired)")
        return 0

    print(f"[wire] candidate goals ({len(targets)}): {targets}")

    planned, skipped = [], []
    for n in targets:
        if not has_sorry_cut_stub(lines, n) and already_wired(lines, n):
            skipped.append((n, "already wired")); continue
        if not has_full_line(lines, n):
            skipped.append((n, "no goal_N_full line in MainTheorem")); continue
        ok, why = bridge_ok(n)
        if not ok:
            skipped.append((n, why)); continue
        planned.append(n)

    for n, why in skipped:
        print(f"  SKIP goal_{n}: {why}")

    if not planned:
        print("[wire] no goals passed preconditions")
        return 1

    all_actions = []
    for n in planned:
        acts = wire_one(lines, n)
        all_actions.append((n, acts))
        for a in acts:
            print(f"  goal_{n}: {a}")

    # (4) CLOSURE stub-cleanup: importing the planned goals transitively pulls in
    # prereq Bridge files that DEFINE their own goal_NN_cut_to_full. Any leftover
    # `goal_NN_cut_to_full := by sorry` stub for a goal in that import closure would
    # collide (`already been declared`). Remove those stubs too. Only touch goals whose
    # Bridge file actually exists (i.e. is a real imported bridge), never bare base goals.
    closure = bridge_import_closure(planned)
    extra_removed = []
    for n in sorted(closure):
        if n in planned:
            continue  # its stub already handled by wire_one
        act = remove_cut_stub(lines, n)
        if act:
            extra_removed.append(n)
            print(f"  [closure] goal_{n}: {act}")
    if extra_removed:
        print(f"[wire] closure stub-cleanup: removed {len(extra_removed)} redundant cut_to_full stubs: {extra_removed}")

    if args.dry_run:
        print(f"[wire] DRY-RUN: would wire {len(planned)} goals, no files written")
        return 0

    open(MT, "w", encoding="utf-8").write("".join(lines))
    print(f"[wire] wrote MainTheorem.lean: wired {len(planned)} goals {planned}")

    if args.no_build:
        print("[wire] --no-build: skipping lake build")
        return 0

    print("[wire] building MainTheorem ...")
    r = subprocess.run(
        ["lake", "build", f"{MODPREFIX}.MainTheorem"],
        cwd=REPO, capture_output=True, text=True)
    errs = [l for l in r.stdout.splitlines() + r.stderr.splitlines()
            if re.search(r"^error|already been declared|error:", l)]
    if r.returncode == 0 and not errs:
        print(f"[wire] BUILD GREEN ✅  ({len(planned)} goals wired)")
        return 0
    print(f"[wire] BUILD FAILED ❌ (rc={r.returncode}, {len(errs)} errors)")
    for l in errs[:25]:
        print("   ", l)
    return 2

if __name__ == "__main__":
    sys.exit(main())

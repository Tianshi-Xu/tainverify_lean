OP_LEMMA_TABLE = {
    "FW_layernorm": "applyNode_fw_layernorm_out",
    "FW_gelu": "applyNode_fw_gelu_out",
    "FW_view": "applyNode_fw_view_out",
    "FW_transpose": "applyNode_fw_transpose_out",
    "FW_contiguous": "applyNode_fw_contiguous_out",
    "FW_add": "applyNode_fw_add2_out",
    "FW_matmul": "applyNode_fw_matmul_out",
    "FW_linear": "applyNode_fw_linear_out",
    "FW_softmax": "applyNode_fw_softmax_out",
}

def op_call(op: str, ins: list) -> str:
    """Render `fw_layernorm (s 946) (s 603) (s 604)` etc."""
    base = op.replace("FW_", "fw_").lower()
    args = " ".join(f"(s {x})" for x in ins)
    return f"{base} {args}"

def op_call_store(op: str, ins: list, store_expr: str) -> str:
    """Render fw_layernorm (STORE 946) (STORE 603) ..."""
    base = op.replace("FW_", "fw_").lower()
    args = " ".join(f"({store_expr} {x})" for x in ins)
    return f"{base} {args}"

def denote_sm_block(n: int, sm_out: int, sm_op: str, sm_ins: list) -> str:
    helper = OP_LEMMA_TABLE[sm_op]
    return (
f"""-- ========== mini sm_goal_{n} computes {sm_out} ({sm_op}) ==========
theorem denote_sm_goal_{n}_{sm_out} (s : Store) :
    denoteGraph sm_goal_{n} s {sm_out} = {op_call(sm_op, sm_ins)} := by
  simp only [sm_goal_{n}, denoteGraph, List.foldl]
  rw [{helper}]

"""
    )

def denote_pm_block(n: int, tp_tid: int, sm_op: str, pm_node_ins: list,
                    is_first_in_list: bool) -> str:
    """One denote_pm_goal_N_TID theorem (per-rank op, single PM node per tp)."""
    helper = OP_LEMMA_TABLE[sm_op]
    extra = ""
    if not is_first_in_list:
        extra = "\n  congr 1 <;> repeat rw [applyNode_eq_of_not_mem_outs (h := by decide)]"
    return (
f"""theorem denote_pm_goal_{n}_{tp_tid} (s : Store) :
    denoteGraph pm_goal_{n} s {tp_tid} = {op_call(sm_op, pm_node_ins)} := by
  simp only [pm_goal_{n}, denoteGraph, List.foldl]
  repeat rw [applyNode_eq_of_not_mem_outs (h := by decide)]
  rw [{helper}]{extra}

"""
    )

def sm_frame_block(n: int, sm_out: int, sm_op: str, sm_node_idx: int,
                   sm_ins: list) -> str:
    helper = OP_LEMMA_TABLE[sm_op]
    ins_str = ", ".join(str(x) for x in sm_ins)
    prefix_rws = ",\n      ".join(
        f"sm_prefix_eq initSM {sm_node_idx} {t} (by native_decide)" for t in sm_ins)
    return (
f"""-- ========== SM self-frame ==========
theorem sm_frame_{sm_out}_self (initSM : Store) :
    denoteGraph sm initSM {sm_out} = denoteGraph sm_goal_{n} (denoteGraph sm initSM) {sm_out} := by
  rw [denote_sm_goal_{n}_{sm_out}]
  rw [sm_val initSM {sm_node_idx} {sm_out} (by native_decide) (by native_decide)]
  rw [show sm.nodes[{sm_node_idx}]'(by native_decide)
      = {{ rank := 0, op := "OpName.{sm_op}", ins := [{ins_str}], outs := [{sm_out}] }}
      from by native_decide]
  rw [{helper}]
  rw [{prefix_rws}]

"""
    )

def pm_frame_block(n: int, tp_tid: int, tp_rank: int, sm_op: str,
                   pm_node_idx: int, pm_node_ins: list) -> str:
    helper = OP_LEMMA_TABLE[sm_op]
    ins_str = ", ".join(str(x) for x in pm_node_ins)
    prefix_rws = ",\n      ".join(
        f"pm_prefix_eq initPM {pm_node_idx} {t} (by native_decide)" for t in pm_node_ins)
    return (
f"""theorem pm_frame_{tp_tid}_self (initPM : Store) :
    denoteGraph pm initPM {tp_tid}
      = {op_call_store(sm_op, pm_node_ins, "denoteGraph pm initPM")} := by
  rw [pm_val initPM {pm_node_idx} {tp_tid} (by native_decide) (by native_decide)]
  rw [show pm.nodes[{pm_node_idx}]'(by native_decide)
      = {{ rank := {tp_rank}, op := "OpName.{sm_op}", ins := [{ins_str}], outs := [{tp_tid}] }}
      from by native_decide]
  rw [{helper}]
  rw [{prefix_rws}]

"""
    )

def hinitcut_helper(n: int, prereqs: list) -> str:
    # Base case: no prereqs => goal_N_cut_initGoals = initGoals (def-eq),
    # so InitGoalsHold transfers directly with no membership case split.
    if not prereqs:
        return (
f"""-- ========== helper: hInitCut separate lemma (base case, no prereqs) ==========
lemma goal_{n}_hInitCut_helper (Ssm Spm : Store)
    (hinitC : InitGoalsHold pm.numRanks initGoals Ssm Spm) :
    InitGoalsHold pm_goal_{n}.numRanks goal_{n}_cut_initGoals Ssm Spm := by
  have hnr : pm_goal_{n}.numRanks = pm.numRanks := by native_decide
  rw [hnr]; intro g hg
  simp only [goal_{n}_cut_initGoals] at hg
  exact hinitC g hg

"""
        )
    args = "\n    ".join(
        f"(hg{m} : InitGoalHolds pm.numRanks goal_{m} Ssm Spm)"
        for m in prereqs
    )
    # forall_mem form: InitGoalsHold cut_initGoals = (∀ g ∈ initGoals ++ prereqs, ...).
    # `List.forall_mem_append` splits off the initGoals block (= hinitC) and the
    # `forall_mem_cons`/`forall_mem_nil` chain reduces the prereq tail to a tuple.
    # This replaces the old O(n^2) `rcases hg with rfl | rfl | ...` membership split
    # (≈250s on large bridges) with an O(n) simp + a single anonymous-constructor
    # term (≈40-66s). Tuple order = hinitC, then prereqs in `goal_N_prereqs` order,
    # closed by `List.forall_mem_nil _`.
    tuple = ", ".join(["hinitC"] + [f"hg{m}" for m in prereqs] + ["List.forall_mem_nil _"])
    return (
f"""-- ========== helper: hInitCut separate lemma (heartbeat workaround) ==========
lemma goal_{n}_hInitCut_helper (Ssm Spm : Store)
    (hinitC : InitGoalsHold pm.numRanks initGoals Ssm Spm)
    {args} :
    InitGoalsHold pm_goal_{n}.numRanks goal_{n}_cut_initGoals Ssm Spm := by
  have hnr : pm_goal_{n}.numRanks = pm.numRanks := by native_decide
  rw [hnr]
  simp only [InitGoalsHold] at hinitC ⊢
  simp only [goal_{n}_cut_initGoals, goal_{n}_prereqs, List.forall_mem_append,
    List.forall_mem_cons, List.forall_mem_nil, and_true]
  exact ⟨{tuple}⟩

"""
    )

@dataclass
class InputSource:
    tid: int
    kind: str          # "tp" | "ts" | "init"
    upstream: int      # goal id (for tp/ts) or initGoal tid (for init)
    upstream_rank: int = -1  # for tp: rank index in that upstream's tps; -1 otherwise
    shape: list = None
    n_tps: int = -1          # total number of tps in the upstream goal (for tp/ts_tp)

def shape_proof_block(input_sources: list, n: int,
                      sm_tids: set = None, pm_tids: set = None) -> str:
    """Render hXXX_smsh / hXXX_pmsh proofs + StoreShapesHold blocks.

    sm_tids/pm_tids: the InitShapes tid sets for the SM / PM mini-graphs. A shape
    proof is emitted for a side only if the tid actually appears in that side's
    InitShapes; this avoids emitting e.g. h575_pmsh for an SM-only weight whose
    PM-side `.shape` extraction from a sharded `.tps` list is pathological (whnf
    timeout)."""
    # None => no gating (emit both, legacy behavior)
    want_sm = (lambda t: True) if sm_tids is None else (lambda t: t in sm_tids)
    want_pm = (lambda t: True) if pm_tids is None else (lambda t: t in pm_tids)
    # group: ts inputs / tp inputs / init inputs
    # For each tp prereq, generate one `simp + obtain` to extract 4 shapes from .tps
    # For each ts prereq, one extraction from .ts.
    # For each init input, one `hinitC initGoal_W` lookup.
    lines = []
    init_proofs_sm = []
    init_proofs_pm = []
    seen_tp_goals = set()
    tp_extracts = []
    ts_extracts = []
    init_haves = []
    init_shapes_sm = {}
    init_shapes_pm = {}
    tp_shapes_pm = {}     # tid -> hVAR
    ts_shapes_sm = {}     # tid -> hVAR

    for src in input_sources:
        if src.kind == "init":
            w = src.upstream
            init_haves.append(
                f"  have hg{w} := hinitC initGoal_{w} (by simp only [initGoals]; decide)")
            sh_str = ", ".join(str(x) for x in (src.shape or []))
            if want_sm(src.tid):
                init_shapes_sm[src.tid] = f"h{src.tid}_smsh"
                init_proofs_sm.append(
f"""  have h{src.tid}_smsh : (Ssm {src.tid}).shape = [{sh_str}] := by
    have h := hg{w}.1; simp only [initGoal_{w}] at h; exact h""")
            if want_pm(src.tid):
                init_shapes_pm[src.tid] = f"h{src.tid}_pmsh"
                init_proofs_pm.append(
f"""  have h{src.tid}_pmsh : (Spm {src.tid}).shape = [{sh_str}] := by
    have h := hg{w}.2.1; simp only [initGoal_{w}, List.map] at h
    have := congrArg List.head? h; simpa using this""")
        elif src.kind == "init_tp":
            # chunk tid of a sharded init weight: shape lives in initGoal_W.tps.
            # Grouped/extracted per parent W below (init_tp_by_w); register only the
            # side(s) that actually consume the chunk.
            if want_sm(src.tid):
                init_shapes_sm[src.tid] = f"h{src.tid}_smsh"
            if want_pm(src.tid):
                init_shapes_pm[src.tid] = f"h{src.tid}_pmsh"
        elif src.kind == "ts":
            m = src.upstream
            sh_str = ", ".join(str(x) for x in (src.shape or []))
            ts_shapes_sm[src.tid] = f"h{src.tid}_smsh"
            ts_extracts.append(
f"""  have h{src.tid}_smsh : (Ssm {src.tid}).shape = [{sh_str}] := by
    have h := hg{m}.1; simp only [goal_{m}] at h; exact h""")
        elif src.kind == "ts_tp":
            # single-tp upstream: same tid is the goal's ts (sm side) AND a tp (pm side)
            m = src.upstream
            sh_str = ", ".join(str(x) for x in (src.shape or []))
            ts_shapes_sm[src.tid] = f"h{src.tid}_smsh"
            ts_extracts.append(
f"""  have h{src.tid}_smsh : (Ssm {src.tid}).shape = [{sh_str}] := by
    have h := hg{m}.1; simp only [goal_{m}] at h; exact h""")
            # pm side handled below via by_goal grouping
        # tp inputs grouped per upstream goal (one obtain per goal)
    # group tp by upstream goal
    by_goal = {}
    for src in input_sources:
        if src.kind in ("tp", "ts_tp"):
            by_goal.setdefault(src.upstream, []).append(src)
    for m, srcs in sorted(by_goal.items()):
        srcs.sort(key=lambda s: s.upstream_rank)
        for s in srcs:
            tp_shapes_pm[s.tid] = f"h{s.tid}_pmsh"
        # single-tp upstream: `.2.1` simplifies to a BARE equation (not a conjunction);
        # `obtain ⟨..⟩` on an `Eq` diverges, so bind directly via `exact`.
        if len(srcs) == 1 and srcs[0].n_tps == 1:
            s = srcs[0]
            sh_str = ", ".join(str(x) for x in (s.shape or []))
            tp_extracts.append(
f"""  have h{s.tid}_pmsh : (Spm {s.tid}).shape = [{sh_str}] := by
    have h := hg{m}.2.1
    simp only [goal_{m}, List.map, List.cons.injEq, and_true] at h
    exact h""")
        else:
            vars_ = ", ".join(f"h{s.tid}_pmsh" for s in srcs)
            tp_extracts.append(
f"""  have h{m}tp := hg{m}.2.1
  simp only [goal_{m}, List.map, List.cons.injEq, and_true] at h{m}tp
  obtain ⟨{vars_}⟩ := h{m}tp""")

    # init_tp: chunk tids of sharded init weights, grouped per parent initGoal_W.
    # Shapes come from initGoal_W.tps (same value on SM and PM init stores), so we
    # obtain h{tid}_smsh once and alias h{tid}_pmsh to it.
    # A parent W may ALSO be a plain `init` source (its ts weight), which already
    # emitted `have hg{w}`; track those to avoid a duplicate binding.
    hg_emitted = {s.upstream for s in input_sources if s.kind == "init"}
    init_tp_by_w = {}
    for src in input_sources:
        if src.kind == "init_tp":
            init_tp_by_w.setdefault(src.upstream, []).append(src)
    for w, srcs in sorted(init_tp_by_w.items()):
        srcs.sort(key=lambda s: s.upstream_rank)
        if w not in hg_emitted:
            init_haves.append(
                f"  have hg{w} := hinitC initGoal_{w} (by simp only [initGoals]; decide)")
            hg_emitted.add(w)
        sm_vars = ", ".join(f"h{s.tid}_chunksh" for s in srcs)
        tp_extracts.append(
f"""  have h{w}tps := hg{w}.2.1
  simp only [initGoal_{w}, List.map, List.cons.injEq, and_true] at h{w}tps
  obtain ⟨{sm_vars}⟩ := h{w}tps""")
        # alias the side-agnostic chunk shape to whichever side(s) consume it
        for s in srcs:
            if want_sm(s.tid):
                tp_extracts.append(f"  have h{s.tid}_smsh := h{s.tid}_chunksh")
            if want_pm(s.tid):
                tp_extracts.append(f"  have h{s.tid}_pmsh := h{s.tid}_chunksh")

    block = "\n".join(init_haves) + ("\n" if init_haves else "")
    block += "\n".join(init_proofs_sm + init_proofs_pm + ts_extracts + tp_extracts)
    return block, init_shapes_sm, init_shapes_pm, ts_shapes_sm, tp_shapes_pm

def store_shapes_blocks(n: int, sm_shapes: list, pm_shapes: list,
                         shape_var_map_sm: dict, shape_var_map_pm: dict) -> str:
    """Render hSM<N>/hPM<N>: StoreShapesHold via rcases over InitShapes list."""
    n_sm = len(sm_shapes)
    n_pm = len(pm_shapes)
    sm_rcases = " | ".join(["⟨rfl, rfl⟩"] * n_sm)
    pm_rcases = " | ".join(["⟨rfl, rfl⟩"] * n_pm)
    sm_exacts = "\n    ".join(f"· exact {shape_var_map_sm[tid]}" for (tid, _) in sm_shapes)
    pm_exacts = "\n    ".join(f"· exact {shape_var_map_pm[tid]}" for (tid, _) in pm_shapes)
    return (
f"""  have hSM{n} : StoreShapesHold Ssm sm_goal_{n}InitEnv := by
    intro tid sh hsh
    rw [sm_goal_{n}InitEnv] at hsh
    have hmem := mem_of_shapeEnvOfList_eq_some hsh
    simp only [sm_goal_{n}InitShapes, List.mem_cons, List.not_mem_nil, or_false,
               Prod.mk.injEq] at hmem
    rcases hmem with {sm_rcases}
    {sm_exacts}
  have hPM{n} : StoreShapesHold Spm pm_goal_{n}InitEnv := by
    intro tid sh hsh
    rw [pm_goal_{n}InitEnv] at hsh
    have hmem := mem_of_shapeEnvOfList_eq_some hsh
    simp only [pm_goal_{n}InitShapes, List.mem_cons, List.not_mem_nil, or_false,
               Prod.mk.injEq] at hmem
    rcases hmem with {pm_rcases}
    {pm_exacts}
"""
    )

def cut_to_full_block(n: int, sm_out: int, tp_tids: list,
                      prereqs: list, input_sources: list,
                      sm_shapes: list, pm_shapes: list,
                      frame_via_denote: bool = True) -> str:
    have_intermediates = "\n  ".join(
        f"have hg{m} := goal_{m}_intermediate initSM initPM hSM hPM hInit"
        for m in prereqs
    )
    sh_block, m_sm_init, m_pm_init, m_sm_ts, m_pm_tp = shape_proof_block(
        input_sources, n, {t for t, _ in sm_shapes}, {t for t, _ in pm_shapes})
    # merge shape variable maps
    sh_map_sm = {**m_sm_init, **m_sm_ts}
    sh_map_pm = {**m_pm_init, **m_pm_tp}
    # for tp-sourced SM shape (e.g. 946 is goal_271.ts) — also gather from m_sm_ts ✓
    ssh_blocks = store_shapes_blocks(n, sm_shapes, pm_shapes, sh_map_sm, sh_map_pm)
    hgs_args = " ".join(f"hg{m}" for m in prereqs)
    frame_haves = []
    frame_rws = []
    for tp in tp_tids:
        # Default families: pm_frame_tp_self equals the nested final expression, so we
        # first `rw [denote_pm_goal_N_tp]` to bridge Spm tp -> that expr. The multiref-
        # second family states pm_frame_tp_self directly as `... = denoteGraph pm_goal_N
        # ... tp`, so the denote_pm rewrite is unnecessary (and would corrupt the goal).
        if frame_via_denote:
            frame_haves.append(
f"""  have hpm{tp} : Spm {tp} = denoteGraph pm_goal_{n} Spm {tp} := by
    rw [denote_pm_goal_{n}_{tp}]; rw [hSpm]; exact pm_frame_{tp}_self initPM""")
        else:
            frame_haves.append(
f"""  have hpm{tp} : Spm {tp} = denoteGraph pm_goal_{n} Spm {tp} := by
    rw [hSpm]; exact pm_frame_{tp}_self initPM""")
        frame_rws.append(f"hpm{tp}")
    frame_haves_str = "\n".join(frame_haves)
    sm_frame_have = (
f"""  have hsmf : Ssm {sm_out} = denoteGraph sm_goal_{n} Ssm {sm_out} := by
    rw [hSsm]; exact sm_frame_{sm_out}_self initSM""")
    rw_args = "hsmf, " + ", ".join(frame_rws)
    return (
f"""-- ========== Assembly: goal_{n}_cut_to_full ==========
theorem goal_{n}_cut_to_full (h : goal_{n}_stmt_cut) : goal_{n}_stmt := by
  intro initSM initPM hSM hPM hInit
  set Ssm := denoteGraph sm initSM with hSsm
  set Spm := denoteGraph pm initPM with hSpm
  {have_intermediates}
  have hinitC := initGoals_preserved initSM initPM hInit
  have hnr : pm_goal_{n}.numRanks = pm.numRanks := by native_decide
{sh_block}
{ssh_blocks}
  have hInitCut : InitGoalsHold pm_goal_{n}.numRanks goal_{n}_cut_initGoals Ssm Spm :=
    goal_{n}_hInitCut_helper Ssm Spm hinitC {hgs_args}
  have hcut := h Ssm Spm hSM{n} hPM{n} hInitCut
{sm_frame_have}
{frame_haves_str}
  rw [hnr] at hcut
  simp only [goal_{n}, List.map] at hcut ⊢
  rw [{rw_args}]
  exact hcut

theorem goal_{n}_intermediate (initSM initPM : Store)
    (hSM : StoreShapesHold initSM smInitEnv) (hPM : StoreShapesHold initPM pmInitEnv)
    (hInit : InitGoalsHold pm.numRanks initGoals initSM initPM) :
    InitGoalHolds pm.numRanks goal_{n} (denoteGraph sm initSM) (denoteGraph pm initPM) := by
  have hfull : goal_{n}_stmt := goal_{n}_cut_to_full prove_goal_{n}_cut
  have := hfull initSM initPM hSM hPM hInit
  -- [OPTIMIZATION] `simpa [InitGoalHolds, goal_{n}] using this` was ~31s (spike 001,
  -- 2026-07-01): simpa normalizes the entire goal_N_stmt statement including
  -- denoteGraph terms. `unfold InitGoalHolds; simp only [goal_N]; exact this` is
  -- surgical (~sub-second) and equivalent since goal_N is a simple record literal.
  unfold InitGoalHolds
  simp only [goal_{n}]
  exact this

end TrainVerify.Denote.GeneratedGoals
""")

def render_family_a(n: int, ir, topo, probe_map, input_sources, prereqs_in_order: list,
                    imports: list) -> str:
    # validate family-A
    assert not topo.single_tp, f"goal_{n} is single-tp; family-A requires multi-tp"
    assert len(topo.mid_tids) == 0, f"goal_{n} has {len(topo.mid_tids)} mid tensors; family-A requires 0"
    assert len(ir.sm_nodes) == 1
    sm_node = ir.sm_nodes[0]
    sm_out = sm_node.outs[0]
    sm_op = sm_node.op
    sm_ins = sm_node.ins
    tp_tids = topo.final_tps
    pm_tps_node = {nd.outs[0]: nd for nd in ir.pm_nodes if nd.outs[0] in set(tp_tids)}
    pn = len(prereqs_in_order)
    header_inputs = ", ".join(f"{s.tid}<-{s.kind}:{s.upstream}" for s in input_sources)
    text = HEADER.format(
        n=n, sm_op=sm_op, sm_ins=sm_ins, sm_out=sm_out,
        pm_outs=tp_tids, gather_dim=ir.lineage.gatherDim, prereqs=prereqs_in_order,
        pn=pn, input_sources=header_inputs,
        imports="\n".join(f"import {m}" for m in imports),
    )
    text += denote_sm_block(n, sm_out, sm_op, sm_ins)
    text += f"-- ========== mini pm_goal_{n} computes {tp_tids} (per-rank {sm_op}) ==========\n"
    for i, tp in enumerate(tp_tids):
        nd = pm_tps_node[tp]
        text += denote_pm_block(n, tp, sm_op, nd.ins, is_first_in_list=(i == 0))
    sm_probe = probe_map["sm"][sm_out]
    text += sm_frame_block(n, sm_out, sm_op, sm_probe["node_idx"], sm_ins)
    text += f"-- ========== PM self-frames for {tp_tids} ==========\n"
    for tp in tp_tids:
        pnode_idx = probe_map["pm"][tp]["node_idx"]
        nd = pm_tps_node[tp]
        text += pm_frame_block(n, tp, nd.rank, sm_op, pnode_idx, nd.ins)
    text += hinitcut_helper(n, prereqs_in_order)
    text += cut_to_full_block(n, sm_out, tp_tids, prereqs_in_order, input_sources,
                              ir.sm_shapes, ir.pm_shapes)
    return text

